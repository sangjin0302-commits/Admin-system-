/**
 * 사용자 메시지와 FAQ 패턴 매칭.
 * 3개 이상 키워드가 일치하면 사전 작성된 답변을 반환합니다.
 * 일치하지 않으면 null을 반환하여 Anthropic API로 폴스루합니다.
 */
export function findFaqMatch(message: string): string | null {
  const q = message.toLowerCase();

  let bestMatch: { response: string; score: number } | null = null;

  for (const entry of FAQ_RESPONSES) {
    let score = 0;
    for (const pattern of entry.patterns) {
      if (q.includes(pattern.toLowerCase())) {
        score++;
      }
    }

    if (score >= 3 && (!bestMatch || score > bestMatch.score)) {
      bestMatch = { response: entry.response, score };
    }
  }

  // 특수 케이스: 2개 매칭이지만 메시지가 매우 짧은 경우 (단순 질문)
  if (!bestMatch) {
    for (const entry of FAQ_RESPONSES) {
      let score = 0;
      for (const pattern of entry.patterns) {
        if (q.includes(pattern.toLowerCase())) {
          score++;
        }
      }
      // 짧은 메시지(20자 이하)에서 2개 이상 매칭
      if (score >= 2 && q.length <= 20 && (!bestMatch || score > bestMatch.score)) {
        bestMatch = { response: entry.response, score };
      }
    }
  }

  return bestMatch?.response ?? null;
}
