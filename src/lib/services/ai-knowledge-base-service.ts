/**
 * 키워드 기반 지식베이스 검색. 상위 3건 반환.
 */
export function searchKnowledge(query: string): string[] {
  const q = query.toLowerCase();

  const keywordMap: Record<string, string[]> = {
    "비자/체류": ["비자", "체류", "visa", "d-8", "d-10", "f-2", "e-7", "연장", "거주", "구직", "투자", "취업", "체류기간"],
    "행정심판": ["행정심판", "심판", "거부", "처분", "불복", "취소", "재결", "이의"],
    "인허가": ["인허가", "허가", "영업", "음식점", "건설", "등록", "면허", "화물", "운송"],
    "비용/수수료": ["비용", "수수료", "가격", "요금", "얼마", "견적", "돈", "무료"],
    "상담 예약": ["예약", "상담", "방문", "일정", "시간"],
    "사무소 정보": ["위치", "주소", "어디", "연락처", "전화", "영업시간", "오시는"],
    "계약서/사실조사": ["계약서", "계약", "사실조사", "조사", "작성", "대행", "검토"],
    "번역": ["번역", "아랍어", "아랍", "통역", "공증"],
    "업무범위": ["행정사", "업무", "범위", "할 수 있", "뭐", "무엇"],
  };

  type ScoredEntry = { entry: KnowledgeEntry; score: number };
  const scored: ScoredEntry[] = KNOWLEDGE_BASE.map((entry) => {
    let score = 0;
    const keywords = keywordMap[entry.category] ?? [];
    for (const kw of keywords) {
      if (q.includes(kw)) score += 2;
    }
    // question/answer 직접 매칭
    const words = q.split(/\s+/).filter((w) => w.length >= 2);
    for (const w of words) {
      if (entry.question.toLowerCase().includes(w)) score += 1;
      if (entry.answer.toLowerCase().includes(w)) score += 0.5;
    }
    return { entry, score };
  });

  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 3)
    .map((s) => `[${s.entry.category}] Q: ${s.entry.question}\nA: ${s.entry.answer}`);
}

/**
 * 검색 결과를 RAG 컨텍스트 문자열로 포맷.
 */
export function buildRagContext(query: string): string {
  const results = searchKnowledge(query);
  if (results.length === 0) return "";
  return results.join("\n\n---\n\n");
}
