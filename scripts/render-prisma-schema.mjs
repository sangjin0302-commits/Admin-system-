import { mkdir, writeFile, readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";

function normalizeProvider(input) {
  const value = (input ?? "sqlite").trim().toLowerCase();

  if (value === "postgres" || value === "postgresql" || value === "pg") {
    return "postgresql";
  }

  return "sqlite";
}

function getRenderedSchemaPath(rootDir, provider) {
  return path.join(rootDir, "prisma", `schema.${provider}.prisma`);
}

async function renderPrismaSchema(providerInput) {
  const provider = normalizeProvider(providerInput);
  const rootDir = process.cwd();
  const sourcePath = path.join(rootDir, "prisma", "schema.prisma");
  const targetPath = getRenderedSchemaPath(rootDir, provider);
  const source = await readFile(sourcePath, "utf8");

  const rendered = source.replace(
    /datasource db\s*\{([\s\S]*?)provider\s*=\s*"[^"]+"/m,
    (match) => match.replace(/provider\s*=\s*"[^"]+"/, `provider = "${provider}"`)
  );

  await mkdir(path.dirname(targetPath), { recursive: true });
  await writeFile(
    targetPath,
    `// This file is generated by scripts/render-prisma-schema.mjs\n${rendered}`,
    "utf8"
  );

  return { provider, targetPath };
}

const isDirectRun =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (isDirectRun) {
  renderPrismaSchema(process.argv[2])
    .then(({ provider, targetPath }) => {
      console.log(`Rendered Prisma schema for ${provider}: ${targetPath}`);
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}

export { getRenderedSchemaPath, normalizeProvider, renderPrismaSchema };
